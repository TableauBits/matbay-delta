import { getAll639_1, getAll639_2B, getAll639_2T, getAll639_3, getName } from 'all-iso-language-codes';

// Keep this package out of application imports: only the generated lookup ships to browsers.
const pickerCodes = getAll639_2T();
const codes = new Set([...getAll639_1(), ...getAll639_2B(), ...pickerCodes, ...getAll639_3()]);
const names: Record<string, string> = {};

for (const code of [...codes].sort()) {
  const name = getName(code, 'fr');
  if (name) names[code] = name.charAt(0).toUpperCase() + name.slice(1);
}

const languages = pickerCodes.map((code) => ({ code, name: names[code] ?? code }));

const license = await Bun.file(new URL('../node_modules/all-iso-language-codes/LICENSE', import.meta.url)).text();
const output = `/*
 * Generated by bun run generate:languages from all-iso-language-codes.
 * Do not edit directly. Preserve picker order and names for all supported ISO aliases.
 *
${license
  .trim()
  .split(/\r?\n/)
  .map((line) => ` * ${line}`)
  .join('\n')}
 */

export const LANGUAGE_OPTIONS: readonly { code: string; name: string }[] = ${JSON.stringify(languages, null, 2)};

export const LANGUAGE_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(names, null, 2)};
`;

// Use the repository formatter so regenerating produces no formatting-only changes.
const { format, resolveConfig } = await import('prettier');
const target = new URL('../src/app/services/language-data.ts', import.meta.url);
await Bun.write(target, await format(output, { ...(await resolveConfig(target.pathname)), parser: 'typescript' }));
console.log(`Generated ${languages.length} picker options and ${Object.keys(names).length} language names.`);
